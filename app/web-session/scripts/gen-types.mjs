// Generates src/core/generated/session-v2.ts from the hub's JSON schema,
// src/swe/remote/schema/session_v2.json (itself generated from
// src/swe/remote/adapters/events.py). The event types are never written by
// hand: a change to the schema is a change to this file, and
// src/core/generated.test.ts fails while the committed file is stale.
//
//   pnpm gen:types           write the file
//   pnpm gen:types --check   exit 1 when the committed file is stale
//
// The generator reads the part of JSON Schema the hub's schema uses (type,
// const, enum, $ref, properties, required, additionalProperties, items,
// anyOf, oneOf) and refuses anything else, so a new construct fails here
// instead of turning into a wrong type.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SCHEMA_PATH = join(here, "../../../src/swe/remote/schema/session_v2.json");
export const OUTPUT_PATH = join(here, "../src/core/generated/session-v2.ts");

const KNOWN = new Set([
  "$ref",
  "additionalProperties",
  "anyOf",
  "const",
  "description",
  "enum",
  "items",
  "minLength",
  "minimum",
  "oneOf",
  "properties",
  "required",
  "type",
]);

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const key = (name) => (IDENT.test(name) ? name : JSON.stringify(name));
const literal = (value) => JSON.stringify(value);

/** One schema node as a TypeScript type expression. */
function render(node, where, indent) {
  for (const name of Object.keys(node)) {
    if (!KNOWN.has(name)) throw new Error(`${where}: the generator does not read "${name}"`);
  }
  if (node.$ref !== undefined) {
    const prefix = "#/$defs/";
    if (!node.$ref.startsWith(prefix)) throw new Error(`${where}: unreadable $ref ${node.$ref}`);
    return node.$ref.slice(prefix.length);
  }
  if (node.const !== undefined) return literal(node.const);
  if (node.enum !== undefined) return node.enum.map(literal).join(" | ");
  for (const union of ["anyOf", "oneOf"]) {
    if (node[union] !== undefined) {
      return node[union].map((part, i) => render(part, `${where}.${union}[${i}]`, indent)).join(" | ");
    }
  }
  if (node.type === undefined && Object.keys(node).every((name) => name === "description")) return "unknown";
  switch (node.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array": {
      const item = render(node.items, `${where}.items`, indent);
      return /[ |]/.test(item) ? `(${item})[]` : `${item}[]`;
    }
    case "object":
      return renderObject(node, where, indent);
    default:
      throw new Error(`${where}: unreadable type ${node.type}`);
  }
}

function renderObject(node, where, indent) {
  const required = new Set(node.required ?? []);
  const props = node.properties ?? {};
  const pad = "  ".repeat(indent + 1);
  const lines = [];
  for (const [name, child] of Object.entries(props)) {
    const doc = child.description ? `${pad}/** ${child.description} */\n` : "";
    const type = render(child, `${where}.${name}`, indent + 1);
    lines.push(`${doc}${pad}${key(name)}${required.has(name) ? "" : "?"}: ${type};`);
  }
  for (const name of required) {
    if (!(name in props)) throw new Error(`${where}: "${name}" is required but not declared`);
  }
  if (node.additionalProperties === true) lines.push(`${pad}[key: string]: unknown;`);
  if (lines.length === 0) return node.additionalProperties === true ? "Record<string, unknown>" : "Record<string, never>";
  return `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}`;
}

/** The whole generated module, as text. */
export function generate(schema) {
  const defs = schema.$defs ?? {};
  const out = [
    "// GENERATED by app/web-session/scripts/gen-types.mjs from",
    "// src/swe/remote/schema/session_v2.json. Do not edit: run `pnpm gen:types`.",
    "",
  ];
  const constants = schema["x-swe"];
  if (constants) {
    out.push("/** The constants the schema's `x-swe` carries: the version, the header, the timings. */");
    out.push(`export const PROTOCOL = ${JSON.stringify(constants, null, 2)} as const;`, "");
  }
  for (const [name, node] of Object.entries(defs)) {
    if (node.description) out.push(`/** ${node.description} */`);
    out.push(`export type ${name} = ${render(node, name, 0)};`, "");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

export function readSchema() {
  return JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
}

function main(argv) {
  const text = generate(readSchema());
  if (argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT_PATH, "utf8");
    } catch {
      // A missing file is as stale as an old one.
    }
    if (current !== text) {
      console.error("src/core/generated/session-v2.ts is stale: run `pnpm gen:types`.");
      process.exit(1);
    }
    return;
  }
  writeFileSync(OUTPUT_PATH, text);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
